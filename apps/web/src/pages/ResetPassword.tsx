import { useState } from 'react';
import { Link, useSearchParams } from 'react-router-dom';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import { CheckCircle2, KeyRound, Lock } from 'lucide-react';
import { authService } from '../services/api';
import { getErrorMessage } from '../lib/errors';
import { useDocumentTitle } from '../hooks/useData';
import { AuthShell } from '../components/layout/AuthShell';
import { Button } from '../components/ui/Button';
import { Input } from '../components/ui/Fields';

const schema = z
  .object({
    token: z.string().min(10, 'Paste the reset token from the API log'),
    password: z
      .string()
      .min(8, 'Use at least 8 characters')
      .regex(/[A-Z]/, 'Add at least one uppercase letter')
      .regex(/[0-9]/, 'Add at least one number'),
    confirm: z.string().min(1, 'Confirm your new password'),
  })
  .refine((values) => values.password === values.confirm, {
    message: 'Passwords do not match',
    path: ['confirm'],
  });

type FormValues = z.infer<typeof schema>;

export default function ResetPassword() {
  useDocumentTitle('Set a new password');
  const [searchParams] = useSearchParams();
  const [done, setDone] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const {
    register,
    handleSubmit,
    formState: { errors, isSubmitting },
  } = useForm<FormValues>({
    resolver: zodResolver(schema),
    defaultValues: { token: searchParams.get('token') ?? '', password: '', confirm: '' },
  });

  const onSubmit = handleSubmit(async (values) => {
    setError(null);
    try {
      await authService.resetPassword(values.token.trim(), values.password);
      setDone(true);
    } catch (requestError) {
      setError(getErrorMessage(requestError));
    }
  });

  if (done) {
    return (
      <AuthShell
        title="Password updated"
        description="Your password has been changed and every existing session was revoked."
      >
        <div className="flex items-start gap-3 rounded-xl border border-brand-200 bg-brand-50 p-4 text-sm text-brand-800 dark:border-brand-500/30 dark:bg-brand-500/10 dark:text-brand-200">
          <CheckCircle2 className="mt-0.5 h-5 w-5 shrink-0" aria-hidden="true" />
          <p className="text-xs leading-relaxed">
            Sign in again with your new password. If you did not make this change, contact an
            administrator immediately.
          </p>
        </div>
        <Link to="/login" className="mt-5 block">
          <Button className="w-full">Continue to sign in</Button>
        </Link>
      </AuthShell>
    );
  }

  return (
    <AuthShell
      title="Choose a new password"
      description="Paste the reset token generated by the API, then choose a strong new password."
    >
      <form onSubmit={onSubmit} className="space-y-4" noValidate>
        {error ? (
          <p className="rounded-xl border border-rose-200 bg-rose-50 px-3 py-2 text-xs font-medium text-rose-700 dark:border-rose-500/30 dark:bg-rose-500/10 dark:text-rose-300" role="alert">
            {error}
          </p>
        ) : null}
        <Input
          label="Reset token"
          placeholder="Paste the token from the API log"
          leftIcon={<KeyRound className="h-4 w-4" aria-hidden="true" />}
          error={errors.token?.message}
          {...register('token')}
        />
        <Input
          label="New password"
          type="password"
          autoComplete="new-password"
          placeholder="At least 8 characters, 1 uppercase, 1 number"
          leftIcon={<Lock className="h-4 w-4" aria-hidden="true" />}
          error={errors.password?.message}
          {...register('password')}
        />
        <Input
          label="Confirm new password"
          type="password"
          autoComplete="new-password"
          placeholder="Repeat the new password"
          leftIcon={<Lock className="h-4 w-4" aria-hidden="true" />}
          error={errors.confirm?.message}
          {...register('confirm')}
        />
        <Button type="submit" className="w-full" loading={isSubmitting}>
          Update password
        </Button>
      </form>
    </AuthShell>
  );
}
